export interface Location {
    id?: string; // Optional as it may be generated by the backend
    sessionId?: string; // Optional as it may be set by the backend
    latitude: number;
    longitude: number;
    name?: string;
    type?: LocationType;
    createdAt?: string;
    updatedAt?: string;
    
    // Enhanced information for rich popups (Phase 1 improvements)
    photos?: string[];
    rating?: number;
    userRatingsTotal?: number;
    priceLevel?: 1 | 2 | 3 | 4;
    openingHours?: OpeningHours;
    phoneNumber?: string;
    website?: string;
    vicinity?: string;
    placeId?: string;
    isOpen?: boolean;
}

export interface OpeningHours {
    isOpen?: boolean;
    periods?: OpeningPeriod[];
    weekdayText?: string[];
}

export interface OpeningPeriod {
    close?: TimeOfDay;
    open?: TimeOfDay;
}

export interface TimeOfDay {
    day: number;
    time: string;
}

export type LocationType = 'attraction' | 'cafe' | 'hotel' | 'restaurant' | 'transport';

export interface WebSocketEvent<T> {
    type: WebSocketEventType;
    payload: T;
}

export type WebSocketEventType = 'LOCATION_ADDED' | 'LOCATION_REMOVED' | 'MAP_CLEARED';

export interface LocationAddedPayload {
    id: string;
    sessionId: string;
    latitude: number;
    longitude: number;
    name?: string;
    type?: LocationType;
}

export interface LocationRemovedPayload {
    locationId: string;
}

export interface MapClearedPayload {
    sessionId: string;
}
